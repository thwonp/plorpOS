#!/bin/sh
# Build PokeDaisy DS as a libretro core for every port: DSperate (the dsperate-lr wrapper) with the PokeDaisy
# companion layered over it (thwonp/pokedaisy-plorp, linux/libretro-ds/). It is the DS shelf's Core row alternative
# beside DSperate-lr, chosen per game (plorpos-oe0.44). Built in the tortos-toolchain image (Debian, GCC 10, glibc 2.17
# symbols): the Brick's firmware glibc is 2.33. The same file runs on the H700 (BaseOS glibc 2.35), GKD (2.40) and
# Rotate (2.41); it is installed to vendor/cores-brick only, and every payload ships it from there as an extra core.
#
#   mk/build-pokedaisy-ds-core.sh     build, install to vendor/cores-brick
#   POKEDAISY_SRC=/path ...           use that checkout (with third_party/dsperate-lr, recursive) instead of cloning the pin
#
# Needs: docker (podman), the tortos-toolchain image (make toolchain), network (the first clone, and python3 from
# the image's own pinned apt snapshot: the image has no python and the core's DS data header is generated by it).
# ~5 minutes.
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC=${POKEDAISY_SRC:-$HOME/.cache/tortos-pokedaisy-ds-core}
REPO=${POKEDAISY_PLORP:-https://github.com/thwonp/pokedaisy-plorp.git}
PD=${PD_COMMIT:-7ebcf8a1936f68d1c59b879a9311a7a5ab904fde} # plorpos/integration: upstream dev 9c9fd173 + open upstream PRs #564 #565 #566 #525 + the owner's DS companion fixes, 2026-11-08
SHA=${PD_SHA:-15067caaefc4a5efa4fca211cb563df39ac6a7d368d614879ea7e59e89ecd6e0} # sha256 of the stripped core; PD_SHA=- builds an unpinned tree
IMAGE=${TOOLCHAIN_IMAGE:-tortos-toolchain}

command -v docker >/dev/null || { echo "need docker" >&2; exit 1; }
if [ -z "$POKEDAISY_SRC" ]; then
	[ -d "$SRC/.git" ] || git clone -q "$REPO" "$SRC"
	git -C "$SRC" fetch -q origin 2>/dev/null || true
	git -C "$SRC" checkout -q -f "$PD"
	git -C "$SRC" submodule -q update --init --force third_party/dsperate-lr
	git -C "$SRC/third_party/dsperate-lr" submodule -q update --init --force --recursive
	git -C "$SRC" clean -qfdx -e third_party/dsperate-lr
fi
[ -f "$SRC/third_party/dsperate-lr/DSperate/src/core/nds.h" ] || { echo "!! $SRC has no third_party/dsperate-lr/DSperate" >&2; exit 1; }
OUT=${POKEDAISY_DS_OUT:-$HOME/.cache/tortos-pokedaisy-ds-core-out}
mkdir -p "$OUT"

docker run --rm -v "$SRC:/src:z" -v "$OUT:/out:z" -w /src $IMAGE sh -c '
set -e
# python3 for the DS data header (gen_data.py): from the image'"'"'s pinned snapshot, whose Release file is past its expiry by design.
apt-get -o Acquire::Check-Valid-Until=false update -qq >/dev/null
apt-get install -y -qq python3 >/dev/null
# A fresh build dir every time: CMake reads the toolchain file'"'"'s flags only on a first configure. The Cortex-A53 tune is
# the Brick'"'"'s (and fine on the A35 / A55 / A75 of the others); the C++ flags are not set by the toolchain file.
rm -rf /out/* && cmake -S linux/libretro-ds -B /out -DCMAKE_TOOLCHAIN_FILE=/src/libretro/aarch64.cmake \
  -DCMAKE_BUILD_TYPE=Release -DCMAKE_CXX_FLAGS=-mcpu=cortex-a53 -DBUILD_TESTING=OFF -DCMAKE_POLICY_VERSION_MINIMUM=3.5 >/out/cfg.log 2>&1
cmake --build /out -j"$(nproc)" --target pokedaisy_ds_libretro >/out/build.log 2>&1
aarch64-linux-gnu-strip --strip-unneeded -o /out/pokedaisy_ds_libretro.stripped.so /out/pokedaisy_ds_libretro.so
# Never ship one that cannot load on the Brick: it must export the libretro entry points, and need nothing newer than its glibc 2.33.
aarch64-linux-gnu-nm -D --defined-only /out/pokedaisy_ds_libretro.so | grep -q " T retro_run$" \
  || { echo "!! retro_run is not exported" >&2; exit 1; }
g=$(aarch64-linux-gnu-objdump -T /out/pokedaisy_ds_libretro.so | grep -oE "GLIBC_2\.[0-9]+" | sort -uV | tail -1)
echo "glibc: $g"
[ "$(echo "$g" | cut -d. -f2)" -le 33 ] || { echo "!! needs $g, the Brick has 2.33" >&2; exit 1; }
' 2>&1 | tail -6

SO=$OUT/pokedaisy_ds_libretro.stripped.so
[ -f "$SO" ] || { echo "!! build failed (see $OUT/build.log)" >&2; exit 1; }
GOT=$(sha256sum "$SO" | cut -d' ' -f1)
if [ -n "$SHA" ] && [ "$SHA" != "-" ] && [ "$GOT" != "$SHA" ]; then
	echo "!! pokedaisy DS core sha256 $GOT, expected $SHA" >&2
	echo "  The toolchain image or the source changed. Verify the core, then update PD_SHA here." >&2
	exit 1
fi
mkdir -p "$ROOT/vendor/cores-brick"
cp "$SO" "$ROOT/vendor/cores-brick/pokedaisy_ds_libretro.so"
echo "  built  pokedaisy DS core ($(git -C "$SRC" rev-parse --short HEAD 2>/dev/null || echo local)) for Brick"
echo "  sha256 $GOT"
